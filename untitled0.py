import torch
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    roc_auc_score,
    confusion_matrix,
)
from model import MythicThreatClassifier, FEATURE_COLUMNS

# 1. Загрузка и выравнивание данных по encounter_id
X_df = pd.read_csv("test_dataset.csv")
y_df = pd.read_csv("test_labels.csv")
df = pd.merge(X_df, y_df, on="encounter_id")

X = torch.tensor(df[FEATURE_COLUMNS].values, dtype=torch.float32)
y_true = df["is_catastrophic_threat"].values

models_paths = {
    "ARES": "models/model_ares.pth",
    "ATHENA": "models/model_athena.pth",
    "APOLLO": "models/model_apollo.pth",
}

results = []
conf_matrices = {}

# 2. Оценка каждой модели при пороге 0.50
for name, path in models_paths.items():
    model = MythicThreatClassifier()
    ckpt = torch.load(path, map_location="cpu", weights_only=True)

    # На случай, если чекпоинт сохранён как словарь с ключом state_dict
    if isinstance(ckpt, dict) and "state_dict" in ckpt:
        ckpt = ckpt["state_dict"]
    elif isinstance(ckpt, dict) and "model_state_dict" in ckpt:
        ckpt = ckpt["model_state_dict"]

    model.load_state_dict(ckpt)
    model.eval()

    with torch.no_grad():
        logits = model(X)
        probs = torch.sigmoid(logits).numpy()

    y_pred = (probs >= 0.50).astype(int)
    tn, fp, fn, tp = confusion_matrix(y_true, y_pred).ravel()
    conf_matrices[name] = np.array([[tn, fp], [fn, tp]])

    results.append({
        "Model": name,
        "Accuracy": accuracy_score(y_true, y_pred),
        "Recall (TPR)": recall_score(y_true, y_pred, zero_division=0),
        "Precision": precision_score(y_true, y_pred, zero_division=0),
        "F1": f1_score(y_true, y_pred, zero_division=0),
        "ROC_AUC": roc_auc_score(y_true, probs),
        "TP (поймано угроз)": int(tp),
        "FN (пропущено угроз)": int(fn),
        "FP (ложных тревог)": int(fp),
        "TN": int(tn),
    })

res_df = pd.DataFrame(results)
print("\n=== СРАВНЕНИЕ МОДЕЛЕЙ (порог = 0.50) ===")
print(res_df.to_string(index=False, float_format=lambda x: f"{x:.4f}"))

# 3. Выбор лучшей модели: максимум Recall (минимум FN), при равенстве — максимум F1
best_row = res_df.sort_values(by=["Recall (TPR)", "F1"], ascending=False).iloc[0]
best_name = best_row["Model"]

print(f"\nЛучшая модель для защиты Дельф: {best_name}")
print(f"FLAG: SIGMOID_{best_name}")

# 4. Визуализация Confusion Matrix для отчёта/доказательства на платформе
fig, axes = plt.subplots(1, 3, figsize=(13, 4))
for ax, (name, cm) in zip(axes, conf_matrices.items()):
    im = ax.imshow(cm, cmap="Blues")
    ax.set_title(f"{name}\nRecall={res_df.loc[res_df['Model']==name, 'Recall (TPR)'].values[0]:.2f}")
    ax.set_xticks([0, 1])
    ax.set_yticks([0, 1])
    ax.set_xticklabels(["Pred 0", "Pred 1"])
    ax.set_yticklabels(["True 0", "True 1"])
    for i in range(2):
        for j in range(2):
            ax.text(j, i, str(cm[i, j]), ha="center", va="center", color="black", fontsize=12, fontweight="bold")

plt.tight_layout()
plt.savefig("confusion_matrices.png", dpi=150)
print("График матриц ошибок сохранён в confusion_matrices.png")

